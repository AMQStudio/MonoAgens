//! Phase-3 `body-sim-actuator`: pure simulation body exposing continuous/physical capabilities
//! (`sim.move`, `sim.stop`) with declared `(channel, window_ms, noise, delta_pred)` effects,
//! Option A cancellation receipts, and simulated sensor percepts answering predictions.

#![forbid(unsafe_code)]

use std::collections::HashSet;

use monoagens_body_kit::{
    BargeInToken, capability_schema_hash, make_refused_receipt, make_terminal_receipt,
};
use monoagens_body_sdk::{
    ActionCancelParams, ActionCancelResult, ActionExecuteParams, ActionExecuteResult, ActionId,
    ActorId, ApprovalResolveParams, ApprovalResolveResult, Audience, BodyDiscoverParams,
    BodyDiscoverResult, BodyHandler, BodyId, CURRENT_PROTOCOL_VERSION, CapabilityDescriptor,
    CapabilityFlags, CapabilityId, ChannelId, ChannelPrediction, CorrelationId, OpaquePayload,
    OriginActor, PerceptEmitParams, PerceptEmitResult, PlaceId, ReceiptOutcome, SensedEffect,
    Taint, TerminationReason, Time, Waist2Error, Waist2Headers, sort_capabilities,
};
use serde::{Deserialize, Serialize};
use serde_json::json;

/// Default Waist-2 body ID for `body-sim-actuator`.
pub const DEFAULT_BODY_ID: &str = "body-sim-actuator";
/// Default simulation place owned by `body-sim-actuator`.
pub const DEFAULT_SIM_PLACE: &str = "sim:actuator-0";
/// Default operator actor for simulated sensor percepts.
pub const DEFAULT_SIM_ACTOR: &str = "per_sim_actuator";

/// Simulated physical command decoded from `action/execute` payload.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SimMoveCommand {
    pub target_delta: f64,
    #[serde(default = "default_steps")]
    pub steps: u32,
}

const fn default_steps() -> u32 {
    4
}

/// Simulated actuator state exposed for deterministic tests.
#[derive(Debug, Clone, PartialEq)]
pub struct SimActuatorState {
    pub position: f64,
    pub velocity: f64,
    pub stopped: bool,
}

impl Default for SimActuatorState {
    fn default() -> Self {
        Self {
            position: 0.0,
            velocity: 0.0,
            stopped: true,
        }
    }
}

/// Pure simulation Waist-2 body implementing `sim.move` and `sim.stop`.
pub struct SimActuatorBody {
    body_id: BodyId,
    place: PlaceId,
    actor: ActorId,
    state: SimActuatorState,
    barge_in: BargeInToken,
    held_actions: HashSet<ActionId>,
    emitted_percepts: Vec<PerceptEmitParams>,
    clock_now_ms: u64,
}

impl Default for SimActuatorBody {
    fn default() -> Self {
        Self::new(
            BodyId::new(DEFAULT_BODY_ID),
            PlaceId::new(DEFAULT_SIM_PLACE),
            ActorId::new(DEFAULT_SIM_ACTOR),
        )
    }
}

impl SimActuatorBody {
    /// Creates a new [`SimActuatorBody`] owning `place`.
    #[must_use]
    pub fn new(body_id: BodyId, place: PlaceId, actor: ActorId) -> Self {
        Self {
            body_id,
            place,
            actor,
            state: SimActuatorState::default(),
            barge_in: BargeInToken::new(),
            held_actions: HashSet::new(),
            emitted_percepts: Vec::new(),
            clock_now_ms: 0,
        }
    }

    /// Returns current simulated physical state.
    #[must_use]
    pub const fn state(&self) -> &SimActuatorState {
        &self.state
    }

    /// Returns simulated sensor percepts generated by completed or partial motions.
    #[must_use]
    pub fn emitted_percepts(&self) -> &[PerceptEmitParams] {
        &self.emitted_percepts
    }

    /// Triggers external preemption (e.g. physical obstacle / e-stop) mid-motion.
    pub fn trigger_external_preempt(&self) {
        self.barge_in.trigger_external();
    }

    /// Advances the virtual clock timestamp used on receipts and percepts.
    pub fn set_now_ms(&mut self, now_ms: u64) {
        self.clock_now_ms = now_ms;
    }

    fn descriptors(&self) -> Vec<CapabilityDescriptor> {
        let mut caps = vec![
            CapabilityDescriptor {
                id: CapabilityId::new("sim.move"),
                description: "Move simulated actuator by target_delta across bounded steps"
                    .to_owned(),
                places: vec![self.place.clone()],
                flags: CapabilityFlags {
                    communicative: false,
                    identity_changing: false,
                    irreversible: false,
                },
                typical_latency_ms: 200,
                capability_schema_hash: capability_schema_hash(&json!({
                    "capability": "sim.move",
                    "type": "object",
                    "properties": {
                        "target_delta": { "type": "number" },
                        "steps": { "type": "integer" }
                    }
                })),
                sensed_effect: Some(SensedEffect {
                    channel: ChannelId::new("sim:encoder:position"),
                    window_ms: 200,
                    noise: 0.02,
                    delta_pred: 1.0,
                }),
            },
            CapabilityDescriptor {
                id: CapabilityId::new("sim.stop"),
                description: "Halt simulated actuator motion immediately".to_owned(),
                places: vec![self.place.clone()],
                flags: CapabilityFlags {
                    communicative: false,
                    identity_changing: false,
                    irreversible: false,
                },
                typical_latency_ms: 20,
                capability_schema_hash: capability_schema_hash(&json!({
                    "capability": "sim.stop",
                    "type": "object",
                    "properties": {}
                })),
                sensed_effect: Some(SensedEffect {
                    channel: ChannelId::new("sim:encoder:velocity"),
                    window_ms: 50,
                    noise: 0.01,
                    delta_pred: -1.0,
                }),
            },
            CapabilityDescriptor {
                id: CapabilityId::new("sim.reset"),
                description: "Reset simulated actuator position to zero".to_owned(),
                places: vec![self.place.clone()],
                flags: CapabilityFlags {
                    communicative: false,
                    identity_changing: false,
                    irreversible: false,
                },
                typical_latency_ms: 10,
                capability_schema_hash: capability_schema_hash(&json!({
                    "capability": "sim.reset",
                    "type": "object",
                    "properties": {}
                })),
                sensed_effect: Some(SensedEffect {
                    channel: ChannelId::new("sim:encoder:position"),
                    window_ms: 50,
                    noise: 0.0,
                    delta_pred: 0.0,
                }),
            },
        ];
        sort_capabilities(&mut caps);
        caps
    }

    fn record_sensor_percept(
        &mut self,
        action_id: &ActionId,
        audience: Audience,
        channel: &str,
        delta_obs: f64,
        delta_pred: f64,
    ) {
        let payload = json!({
            "channel": channel,
            "position": self.state.position,
            "velocity": self.state.velocity,
            "delta_obs": delta_obs,
            "delta_pred": delta_pred,
        })
        .to_string();

        self.emitted_percepts.push(PerceptEmitParams {
            headers: Waist2Headers::new(format!("sim-sensor-{}", action_id)),
            actor: self.actor.clone(),
            origin_actor: Some(OriginActor::new(self.actor.clone())),
            place: self.place.clone(),
            audience: Some(audience),
            timestamp_ms: Time::from_millis(self.clock_now_ms),
            payload: OpaquePayload::from_bytes(payload.into_bytes()),
            taint: Taint::Trusted,
            addressees: Vec::new(),
            named: Vec::new(),
            orient: Vec::new(),
            reply_to: None,
            correlation_id: Some(CorrelationId::new(action_id.as_str())),
            channel: Some(ChannelId::new(channel)),
            delta_obs: Some(delta_obs),
            channel_prediction: Some(ChannelPrediction {
                channel: ChannelId::new(channel),
                delta_obs: Some(delta_obs),
                delta_pred: Some(delta_pred),
            }),
            length: None,
            negative_flag: None,
            repair: None,
            continued_attention: None,
            f_modal: None,
            embeddings: Vec::new(),
            attachments: Vec::new(),
            dialogue_act_gap: None,
            peer_expertise_margin: None,
        });
    }
}

impl BodyHandler for SimActuatorBody {
    fn discover(&mut self, params: BodyDiscoverParams) -> Result<BodyDiscoverResult, Waist2Error> {
        Ok(BodyDiscoverResult {
            body_id: params.body_id.unwrap_or_else(|| self.body_id.clone()),
            protocol_version: CURRENT_PROTOCOL_VERSION,
            capabilities: self.descriptors(),
            places: vec![self.place.clone()],
        })
    }

    fn execute(&mut self, params: ActionExecuteParams) -> Result<ActionExecuteResult, Waist2Error> {
        if params.audience.is_empty() {
            return Err(Waist2Error::undeclared_audience());
        }
        let known = matches!(
            params.capability_id.as_str(),
            "sim.move" | "sim.stop" | "sim.reset"
        );
        if !known {
            return Err(Waist2Error::unknown_capability(&params.capability_id));
        }

        let place_ok = !params.places.is_empty() && params.places.iter().all(|p| p == &self.place);
        if !place_ok {
            let receipt = make_refused_receipt(
                params.action_id,
                params.capability_id,
                "ERR_UNKNOWN_PLACE",
                "action targets a place not owned by body-sim-actuator",
                params.h_act,
                Time::from_millis(self.clock_now_ms),
            );
            return Ok(ActionExecuteResult {
                accepted: false,
                receipt: Some(receipt),
            });
        }

        if params.h_act.is_some() && params.payload.as_bytes() == b"hold" {
            self.held_actions.insert(params.action_id.clone());
            let receipt = make_terminal_receipt(
                params.action_id,
                params.capability_id,
                ReceiptOutcome::Held,
                Some("PendingApproval".to_owned()),
                Some("awaiting operator approval for actuator motion".to_owned()),
                Some(TerminationReason::Normal),
                Some(0.0),
                Some(0),
                params.h_act,
                Time::from_millis(self.clock_now_ms),
            );
            return Ok(ActionExecuteResult {
                accepted: true,
                receipt: Some(receipt),
            });
        }

        let now = Time::from_millis(self.clock_now_ms);
        if params.capability_id.as_str() == "sim.stop" {
            let prev_vel = self.state.velocity;
            self.state.velocity = 0.0;
            self.state.stopped = true;
            self.record_sensor_percept(
                &params.action_id,
                params.audience,
                "sim:encoder:velocity",
                -prev_vel,
                -1.0,
            );
            let receipt = make_terminal_receipt(
                params.action_id,
                params.capability_id,
                ReceiptOutcome::Done,
                None,
                Some("actuator halted".to_owned()),
                Some(TerminationReason::Normal),
                Some(1.0),
                Some(1),
                params.h_act,
                now,
            );
            return Ok(ActionExecuteResult {
                accepted: true,
                receipt: Some(receipt),
            });
        }

        if params.capability_id.as_str() == "sim.reset" {
            self.state.position = 0.0;
            self.state.velocity = 0.0;
            self.state.stopped = true;
            self.record_sensor_percept(
                &params.action_id,
                params.audience,
                "sim:encoder:position",
                0.0,
                0.0,
            );
            let receipt = make_terminal_receipt(
                params.action_id,
                params.capability_id,
                ReceiptOutcome::Done,
                None,
                Some("position reset to 0".to_owned()),
                Some(TerminationReason::Normal),
                Some(1.0),
                Some(0),
                params.h_act,
                now,
            );
            return Ok(ActionExecuteResult {
                accepted: true,
                receipt: Some(receipt),
            });
        }

        // sim.move
        let cmd: SimMoveCommand =
            serde_json::from_slice(params.payload.as_bytes()).unwrap_or(SimMoveCommand {
                target_delta: 1.0,
                steps: 4,
            });
        let steps = cmd.steps.max(1);
        let step_delta = cmd.target_delta / f64::from(steps);
        let mut completed_steps: u64 = 0;

        self.state.stopped = false;
        self.state.velocity = step_delta;

        for _ in 0..steps {
            if self.barge_in.is_triggered() {
                let reason = self.barge_in.termination_reason();
                let reason_code = match reason {
                    TerminationReason::CanceledByCore => "canceled_by_core",
                    _ => "preempted_external",
                };
                self.barge_in = BargeInToken::new();
                self.state.velocity = 0.0;
                self.state.stopped = true;
                let obs_delta = step_delta * (completed_steps as f64);
                self.record_sensor_percept(
                    &params.action_id,
                    params.audience,
                    "sim:encoder:position",
                    obs_delta,
                    cmd.target_delta,
                );
                let receipt = make_terminal_receipt(
                    params.action_id,
                    params.capability_id,
                    ReceiptOutcome::Failed,
                    Some(reason_code.to_owned()),
                    Some(format!("motion halted at {completed_steps}/{steps} steps")),
                    Some(reason),
                    Some(completed_steps as f32 / steps as f32),
                    Some(completed_steps),
                    params.h_act,
                    now,
                );
                return Ok(ActionExecuteResult {
                    accepted: true,
                    receipt: Some(receipt),
                });
            }
            self.state.position += step_delta;
            completed_steps += 1;
        }

        self.state.velocity = 0.0;
        self.state.stopped = true;
        self.record_sensor_percept(
            &params.action_id,
            params.audience,
            "sim:encoder:position",
            cmd.target_delta,
            cmd.target_delta,
        );

        let receipt = make_terminal_receipt(
            params.action_id,
            params.capability_id,
            ReceiptOutcome::Done,
            None,
            Some(format!("position={:.3}", self.state.position)),
            Some(TerminationReason::Normal),
            Some(1.0),
            Some(completed_steps),
            params.h_act,
            now,
        );
        Ok(ActionExecuteResult {
            accepted: true,
            receipt: Some(receipt),
        })
    }

    fn cancel(&mut self, params: ActionCancelParams) -> Result<ActionCancelResult, Waist2Error> {
        self.barge_in.trigger_core_cancel();
        self.state.velocity = 0.0;
        self.state.stopped = true;
        let receipt = make_terminal_receipt(
            params.action_id,
            CapabilityId::new("sim.move"),
            ReceiptOutcome::Failed,
            Some("canceled_by_core".to_owned()),
            params.reason,
            Some(TerminationReason::CanceledByCore),
            Some(0.0),
            Some(0),
            None,
            Time::from_millis(self.clock_now_ms),
        );
        Ok(ActionCancelResult {
            cancelled: true,
            receipt: Some(receipt),
        })
    }

    fn resolve_approval(
        &mut self,
        params: ApprovalResolveParams,
    ) -> Result<ApprovalResolveResult, Waist2Error> {
        if self.held_actions.remove(&params.action_id) {
            if params.approved {
                self.state.position += 1.0;
            }
            return Ok(ApprovalResolveResult { applied: true });
        }
        Ok(ApprovalResolveResult { applied: false })
    }

    fn on_percept(&mut self, params: PerceptEmitParams) -> Result<PerceptEmitResult, Waist2Error> {
        if params.audience.as_ref().is_none_or(Audience::is_empty) {
            return Err(Waist2Error::undeclared_audience());
        }
        if params.place != self.place {
            return Err(Waist2Error::invalid_receipt_transition(format!(
                "percept place '{}' is not owned by body-sim-actuator",
                params.place
            )));
        }
        Ok(PerceptEmitResult { accepted: true })
    }
}
